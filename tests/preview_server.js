http.createServer((req, res) => {
  const url = new URL(req.url, HERE);
  const p = decodeURIComponent(url.pathname);

  if (p.startsWith('/rest/v1/rpc/')) {
    if (req.method !== 'POST') { send(res, 405, 'text/plain', 'POST only'); return; }
    let body = '';
    req.on('data', c => { body += c; });
    req.on('end', () => {
      const fn = p.slice('/rest/v1/rpc/'.length);
      sb.nowMs = Date.now();
      try {
        const out = sb.handle(fn, body ? JSON.parse(body) : {});
        console.log('rpc ' + fn + (out && out.ok === false ? ' -> ' + out.error : ''));
        send(res, 200, 'application/json', JSON.stringify(out));
      } catch (e) {
        console.log('rpc ' + fn + ' THREW ' + e.message);
        send(res, 500, 'text/plain', 'the fake threw: ' + e.stack);
      }
    });
    return;
  }
  if (p === '/__token' || p === '/__signin') {
    const who = url.searchParams.get('who');
    const auth = signIn(who);
    if (!auth) { send(res, 400, 'text/plain', 'who is one of: ' + Object.keys(PEOPLE).join(', ')); return; }
    if (p === '/__token') { send(res, 200, 'text/plain', auth.token); return; }
    const js = v => JSON.stringify(v).replace(/</g, '\\u003c');
    // A device remembered in an earlier preview (schema v18) would win over
    // this sign-in, so that's forgotten first.
    send(res, 200, 'text/html; charset=utf-8', '<!doctype html><meta charset="utf-8"><script>' +
      "localStorage.removeItem('mog_hq_token');localStorage.removeItem('mog_hq_roles');" +
      "sessionStorage.setItem('mog_hq_token', " + js(auth.token) + ");sessionStorage.setItem('mog_hq_roles', " + js(JSON.stringify(auth.roles)) +
      ");location.replace('/hq/');</script>");
    return;
  }
  if (p === '/') { send(res, 200, 'text/html; charset=utf-8', home()); return; }
  if (TREES.some(([prefix]) => p === prefix.slice(0, -1))) { res.writeHead(302, { Location: p + '/' }); res.end(); return; }

  const file = fileFor(p);
  if (!file) { send(res, 404, 'text/plain', 'not served here'); return; }
  fs.readFile(file, (e, buf) => {
    if (e) { send(res, 404, 'text/plain', 'not found'); return; }
    const ext = path.extname(file);
    let out = buf;
    if (ext === '.html' || ext === '.js' || ext === '.json') {
      out = buf.toString('utf8').split(REAL).join(HERE);
      if (/https:\/\/[a-z0-9]+\.supabase\.co/.test(out)) {
        send(res, 500, 'text/plain', p + ' names a Supabase address other than ' + REAL + ', so it is not served (it could reach a real store)');
        return;
      }
    }
    send(res, 200, TYPES[ext] || 'application/octet-stream', out);
  });
}).on('error', e => {
  console.error('preview: ' + e.message + (e.code === 'EADDRINUSE' ? ' (another preview holds it: stop that one, or pass --port)' : ''));
  process.exit(1);
}).listen(PORT, '127.0.0.1', () => {
  const stale = hqStale();
  if (stale.length) console.log('preview: hq/ does not match template/ (' + stale.join(', ') + '): run python build.py, then reload /hq/');
  console.log('preview on ' + HERE + '/ : the app ' + HERE + '/' + APP + '/ (PIN ' + PIN + '), HQ ' + HERE + '/__signin?who=both');
});
