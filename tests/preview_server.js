function moveFromSheet(sb, slug, seed) {
  const spec = makeStore(seed, { realistic: true });
  const master = spec.sheets.MASTER_ITEMS, seen = new Set();
  spec.sheets.MASTER_ITEMS = [master[0]].concat(master.slice(1).filter(r => {   // one row per item id (history_app)
    const id = String(r[0] || '').trim();
    if (!id || seen.has(id)) return false;
    seen.add(id);
    r[1] = NAMES[ITEM_IDS.indexOf(id)] || r[1];
    return true;
  }));
  for (const r of spec.sheets.LOG_ORDERS.slice(1)) r[4] = NAMES[ITEM_IDS.indexOf(r[3])] || r[4];
  // The fixture's pick path names these areas but its Sheet doesn't list them (SETUP H:I).
  AREAS.forEach(([name, ord], i) => { const row = spec.sheets.SETUP[i + 1] || (spec.sheets.SETUP[i + 1] = []); row[7] = name; row[8] = ord; });
  sb.nowMs = spec.now;
  const key = sb.provision(slug);
  const side = F.makeContext(Object.assign({}, spec, { scriptProps: Object.assign({}, spec.scriptProps,
    { MOG_SUPABASE_SLUG: slug, MOG_SUPABASE_SYNC_KEY: key, MOG_BACKEND: 'supabase', MOG_API_PIN: PIN }) }), {
    console: QUIET, UrlFetchApp: sb.urlFetchApp(), ScriptApp: fakeScriptApp(), ContentService: fakeContentService,
    LockService: { getDocumentLock: () => ({ waitLock() {}, tryLock() { return true; }, releaseLock() {}, hasLock() { return true; } }) },
    Session: { getScriptTimeZone: () => 'UTC', getActiveUser: () => ({ getEmail: () => '' }), getEffectiveUser: () => ({ getEmail: () => '' }) }
  });
  SERVER.runInContext(side.ctx);
  const run = fn => { NEW_EXECUTION.runInContext(side.ctx); return fn(side.ctx); };
  run(c => c.pushPinsNow_());
  run(c => c.pushCatalogNow_());
  run(c => c.setDbStateFromSheet_());
  run(c => c.importSheetCountsToDb_());
  run(c => c.supabaseSync_('mog_sync_seed_catalog', { p_tables: c.buildCatalogTables_().tables }));
  run(c => c.backfillOrderLogToDb_());
  return sb.stores.get(slug);
}

