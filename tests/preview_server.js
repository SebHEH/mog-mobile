// hq/ is generated by the full build. Say so when it no longer matches template/.
function hqStale() {
  const read = f => { try { return fs.readFileSync(path.join(F.REPO, f), 'utf8').replace(/\r\n/g, '\n'); } catch (e) { return null; } };
  const out = [];
  const parts = (read('template/hq/index.html') || '').split('/*__MOG_HQ__*/null');
  const page = read('hq/index.html');
  if (parts.length !== 2 || page === null || !page.startsWith(parts[0]) || !page.endsWith(parts[1])) out.push('index.html');
  if (read('hq/catalogEdit.js') !== read('template/editor/catalogEdit.js')) out.push('catalogEdit.js');
  for (const f of fs.readdirSync(path.join(F.REPO, 'template', 'hq'))) {
    if (/\.(js|svg)$/.test(f) && read('hq/' + f) !== read('template/hq/' + f)) out.push(f);
  }
  return out;
}

