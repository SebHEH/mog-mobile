const esc = s => String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const send = (res, status, type, body) => { res.writeHead(status, { 'Content-Type': type, 'Cache-Control': 'no-store' }); res.end(body); };

function fileFor(p) {
  if (p === '/manifest.json') return path.join(F.REPO, 'manifest.json');   // the app links ../manifest.json
  const tree = TREES.find(([prefix]) => p.startsWith(prefix));
  if (!tree) return null;
  const base = path.resolve(F.REPO, tree[1]);
  const file = path.resolve(base, '.' + p.slice(tree[0].length - 1) + (p.endsWith('/') ? 'index.html' : ''));
  return file.startsWith(base + path.sep) ? file : null;
}

